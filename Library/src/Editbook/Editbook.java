    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
          PreparedStatement pst;
            Connection C=Connect.getCon();
        try {
            pst=C.prepareStatement("update addbook set Name=?,Publisher=?,Year=?,Price=? where BookId=?");
            pst.setString(1, txtname.getText());
            pst.setString(2, txtpublisher.getText());
            pst.setString(3, txtyear.getText());
            pst.setString(4, txtprice.getText());
            pst.setString(5, txtbookid.getText());
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this,  "Edited Book ");
        } catch (SQLException ex) {
            Logger.getLogger(Editbook.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed


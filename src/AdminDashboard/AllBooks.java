private void displayBooksWithRSMetroTable() {
     DefaultTableModel model = new DefaultTableModel(new Object[]{"Book ID", "Name", "Publisher", "Year","Price","Quantity"}, 0);
availablebooks.setModel(model);

    try {
        Connection con = DBconnection.getConnection();
        String sql = "SELECT * FROM books WHERE Quantity >= 0 ORDER BY Quantity ASC";
        Statement stmt = con.createStatement();
        ResultSet rs = stmt.executeQuery(sql);

        while (rs.next()) {
            String bookId = rs.getString("BookID");
            String name = rs.getString("Name");
            String author = rs.getString("Publisher");
            String year = rs.getString("Year");
            String price = rs.getString("Price");
            int quantity = rs.getInt("Quantity");

            model.addRow(new Object[]{bookId, name, author,year,price, quantity});
        }

        rs.close();
        stmt.close();
        con.close();
    } catch (Exception e) {
        e.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "Error fetching book data: " + e.getMessage());
    }

    
}


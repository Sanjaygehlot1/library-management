    private void availablebooksComponentShown(java.awt.event.ComponentEvent evt) {//GEN-FIRST:event_availablebooksComponentShown

        Connection con = null;
        Statement st = null;
        ResultSet rs = null;

        try {
            con = DBconnection.getConnection();
            st = con.createStatement();

            String studentID = "33";
            String query = "SELECT issue.BookID, books.Name, issue.IssueDate, issue.Duedate " +
            "FROM issue " +
            "INNER JOIN books ON books.BookID = issue.BookID " +
            "WHERE issue.StudentID = '" + studentID + "' AND issue.Returned = 'NO'";

            rs = st.executeQuery(query);
            availablebooks.setModel(DbUtils.resultSetToTableModel(rs));

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error loading data: " + e.getMessage());
        } finally {
            try {
                if (rs != null) rs.close();
                if (st != null) st.close();
                if (con != null) con.close();
            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    }//GEN-LAST:event_availablebooksComponentShown


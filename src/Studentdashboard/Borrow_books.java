    private void IssuebtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_IssuebtnActionPerformed
   String bookID = txt_bookid.getText();
    String studentID = txt_studentid.getText();
    Date issueDate = txtissuedate.getDatoFecha();
    Date dueDate = txtduedate.getDatoFecha();
    
    if (bookID.isEmpty() || studentID.isEmpty() || issueDate == null || dueDate == null) {
        JOptionPane.showMessageDialog(null, "Please fill in all fields before issuing.");
        return;
    }

    Connection conn = null;
    PreparedStatement checkStmt = null;
    PreparedStatement issueStmt = null;
    ResultSet rs = null;

    try {
        // Connect to the database
        conn = ConnectionProvider.getCon();

        // Check if the book is already issued
        String checkQuery = "SELECT * FROM issue WHERE BookID = ? AND StudentID = ? AND Returned='NO'";
        checkStmt = conn.prepareStatement(checkQuery);
        checkStmt.setString(1, bookID);
        checkStmt.setString(2, studentID);
        rs = checkStmt.executeQuery();

        if (rs.next()) {
            JOptionPane.showMessageDialog(null, "This book is already issued to this student.");
            return;
        }

       
        String insertQuery = "INSERT INTO issue (BookID, StudentID, IssueDate, DueDate,Returned) VALUES (?, ?, ?, ?, ?)";
        issueStmt = conn.prepareStatement(insertQuery);
        issueStmt.setString(1, bookID);
        issueStmt.setString(2, studentID);
        issueStmt.setDate(3, new java.sql.Date(issueDate.getTime()));
        issueStmt.setDate(4, new java.sql.Date(dueDate.getTime()));
        issueStmt.setString(5, "NO");
        int rowsInserted = issueStmt.executeUpdate();
        if (rowsInserted > 0) {
            JOptionPane.showMessageDialog(null, "Book issued successfully!");
        } else {
            JOptionPane.showMessageDialog(null, "Failed to issue the book. Please try again.");
        }

    } catch (SQLException ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(null, "Error: " + ex.getMessage());
    } finally {
        // Close resources
        try {
            if (rs != null) rs.close();
            if (checkStmt != null) checkStmt.close();
            if (issueStmt != null) issueStmt.close();
            if (conn != null) conn.close();
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
    }
    }//GEN-LAST:event_IssuebtnActionPerformed


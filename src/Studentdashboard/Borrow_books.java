     private void searchBookAndSetDetails(String bookId, String studentId) {
        Connection conn = null;
        PreparedStatement pstmt = null;
        ResultSet rs = null;

        try {
            // Connect to the database
            conn = ConnectionProvider.getCon();

            // Check if the book is already allotted to the student
            String checkQuery = "SELECT * FROM  issue WHERE BookID = ? AND StudentID = ? AND Returned='NO'";
            pstmt = conn.prepareStatement(checkQuery);
            pstmt.setString(1, bookId);
            pstmt.setString(2, studentId);
            rs = pstmt.executeQuery();

            if (rs.next()) {
                JOptionPane.showMessageDialog(null, "The book is already allotted to this student.");
                return;
            }

            // Fetch book details if it's not already allotted
            String bookQuery = "SELECT Name FROM books WHERE BookID = ?";
            pstmt = conn.prepareStatement(bookQuery);
            pstmt.setString(1, bookId);
            rs = pstmt.executeQuery();

            if (rs.next()) {
                String bookName = rs.getString("Name");
                txt_bookname.setText(bookName);

                // Set today's date as the issue date
                LocalDate today = LocalDate.now();
                Date issueDate = Date.from(today.atStartOfDay(ZoneId.systemDefault()).toInstant());
                txtissuedate.setDatoFecha(issueDate);

                // Set the due date to one month from today
                LocalDate dueDate = today.plusMonths(1);
                Date dueDateValue = Date.from(dueDate.atStartOfDay(ZoneId.systemDefault()).toInstant());
                txtduedate.setDatoFecha(dueDateValue);
            } else {
                JOptionPane.showMessageDialog(null, "Book not found.");
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
        } finally {
            // Close resources
            try {
                if (rs != null) rs.close();
                if (pstmt != null) pstmt.close();
                if (conn != null) conn.close();
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }
